import type { DiagnosticBag } from '../diagnostics.js'
import { FormulaCompiler } from '../formula/compile.js'
import { formulaFunctionName } from '../formula/naming.js'
import type { ComponentIR } from '../ir/types.js'
import { WorkflowCompiler } from '../workflow/compile.js'

export interface WorkflowFileResult {
  content: string
  helpers: Set<string>
  hasWorkflows: boolean
}

export function emitWorkflowFile(
  component: ComponentIR,
  diagnostics: DiagnosticBag,
  projectFormulaResolver?: (
    name: string,
    packageName?: string,
    fromPackage?: string,
  ) => string | undefined,
  customActionResolver?: (name: string, packageName?: string) => string,
): WorkflowFileResult {
  const formulaCompiler = new FormulaCompiler({
    diagnostics,
    componentKey: component.key,
    packageName: component.packageName,
    applyResolver: (name) => `F.${formulaFunctionName(name)}`,
    projectFormulaResolver,
  })
  const workflowCompiler = new WorkflowCompiler({
    componentKey: component.key,
    diagnostics,
    formulaCompiler,
    customActionResolver: (name, packageName) =>
      customActionResolver?.(name, packageName) ??
      (packageName ? `${packageName}/${name}` : name),
  })
  const defs: string[] = []

  for (const [key, workflow] of Object.entries(component.source.workflows ?? {})) {
    if (!workflow) continue
    defs.push(workflowCompiler.compileWorkflow(key, workflow))
  }

  for (const [nodeId, node] of Object.entries(component.source.nodes ?? {})) {
    if (!node) continue
    const events = 'events' in node ? node.events : undefined
    for (const [trigger, event] of Object.entries(events ?? {})) {
      if (!event?.actions.length) continue
      defs.push(workflowCompiler.compileEvent(nodeId, trigger, event.actions))
    }
  }

  for (const [apiName, api] of Object.entries(component.source.apis ?? {})) {
    if (!api) continue
    if (api.client?.onCompleted?.actions.length) {
      defs.push(
        workflowCompiler.compileEvent(apiName, 'completed', api.client.onCompleted.actions),
      )
    }
    if (api.client?.onFailed?.actions.length) {
      defs.push(
        workflowCompiler.compileEvent(apiName, 'failed', api.client.onFailed.actions),
      )
    }
    if (api.client?.onMessage?.actions.length) {
      defs.push(
        workflowCompiler.compileEvent(apiName, 'message', api.client.onMessage.actions),
      )
    }
  }

  if (component.source.onLoad?.actions.length) {
    defs.push(workflowCompiler.compileLifecycle('onLoad', component.source.onLoad.actions))
  }
  if (component.source.onAttributeChange?.actions.length) {
    defs.push(
      workflowCompiler.compileLifecycle(
        'onAttributeChange',
        component.source.onAttributeChange.actions,
      ),
    )
  }

  const helpers = new Set([...formulaCompiler.helpers, ...workflowCompiler.helpers])
  const imports: string[] = [
    `import type {${formulaCompiler.needsNcArgsType ? ' NcArgs,' : ''} NcWorkflowContext } from '~/lib/runtime'`,
  ]
  if (helpers.size) {
    imports.push(`import { ${[...helpers].sort().join(', ')} } from '~/lib/runtime'`)
  }
  if (formulaCompiler.usesApply) {
    imports.push(`import * as F from './${component.vueName}.formulas'`)
  }
  const projectCalls = [...formulaCompiler.projectFormulasUsed]
  if (projectCalls.some((call) => call.startsWith('PF.'))) {
    imports.push(`import * as PF from '~/lib/nordcraft/project-formulas'`)
  }
  if (projectCalls.some((call) => call.startsWith('PKG.'))) {
    imports.push(`import * as PKG from '~/lib/nordcraft/project-formulas'`)
  }

  const content =
    `/* Generated by nordcraft2nuxt from Nordcraft project JSON. Do not edit by hand. */\n` +
    imports.join('\n') +
    '\n\n' +
    (defs.length ? defs.join('\n') : 'export {}\n')

  return {
    content,
    helpers,
    hasWorkflows: defs.length > 0,
  }
}
